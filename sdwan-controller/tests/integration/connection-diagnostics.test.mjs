import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test from 'node:test';
import pg from 'pg';
import loader from '../support/load-ts.cjs';

assert.equal(process.env.FABRIC_TEST_ISOLATED, '1', 'Use npm run test:integration');
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 3 });
const load = loader({ '../db': { getDatabase: () => pool }, 'next/headers': {}, 'next/navigation': {} });
const inventory = load('src/lib/fabric/inventory.ts');
const diagnostics = load('src/lib/fabric/connection-diagnostics.ts');
const enrollment = load('src/lib/fabric/enrollment.ts');
const actor = (await pool.query('SELECT id::text,email,role FROM operators WHERE email=$1', [process.env.FABRIC_TEST_EMAIL])).rows[0];
test.after(() => pool.end());

test('connection diagnostics show accepted evidence, expiry and archive/new-device boundaries without secrets', async () => {
  const node = await inventory.createNode(actor, { name: `Status-${randomUUID()}`, kind: 'branch', mode: 'gateway' });
  assert.equal(node.enrollment.nodeId, node.id);
  await assert.rejects(diagnostics.readConnectionDiagnostics(null, node.id), /Sign in/);
  await assert.rejects(diagnostics.readConnectionDiagnostics(actor, 'invalid'), /Device not found/);
  await assert.rejects(diagnostics.readConnectionDiagnostics(actor, randomUUID()), /not found/);
  let report = await diagnostics.readConnectionDiagnostics({ ...actor, role: 'viewer' }, node.id);
  assert.equal(report.tokenStatus, 'available');
  assert.equal(report.enrolledAt, null);
  assert.match(report.summary, /has not accepted enrollment/);
  assert.match(report.nextStep, /Archiving an entry leaves its local identity/);
  assert.ok(report.events.some(event => event.message === 'Enrollment token issued'));
  assert.ok(!JSON.stringify(report).includes(node.enrollment.token));
  assert.ok(!JSON.stringify(report).includes('token_hash'));
  await pool.query("UPDATE enrollment_tokens SET expires_at=now()-interval '1 minute' WHERE node_id=$1", [node.id]);
  report = await diagnostics.readConnectionDiagnostics(actor, node.id);
  assert.equal(report.tokenStatus, 'expired');
  assert.match(report.summary, /expired/);
  await pool.query('UPDATE nodes SET enrolled_at=now() WHERE id=$1', [node.id]);
  await pool.query('UPDATE enrollment_tokens SET consumed_at=now() WHERE node_id=$1', [node.id]);
  report = await diagnostics.readConnectionDiagnostics(actor, node.id);
  assert.equal(report.tokenStatus, 'consumed');
  assert.match(report.summary, /no management heartbeat/);
  await pool.query('UPDATE nodes SET last_seen_at=now() WHERE id=$1', [node.id]);
  report = await diagnostics.readConnectionDiagnostics(actor, node.id);
  assert.equal(report.connectionStatus, 'syncing');
  await pool.query("INSERT INTO config_acknowledgements(node_id,revision,status) VALUES($1,1,'rejected')", [node.id]);
  report = await diagnostics.readConnectionDiagnostics(actor, node.id);
  assert.match(report.summary, /rejected/);
  assert.ok(report.acknowledgedAt);
  await pool.query("UPDATE config_acknowledgements SET status='received' WHERE node_id=$1", [node.id]);
  assert.equal((await diagnostics.readConnectionDiagnostics(actor, node.id)).connectionStatus, 'management-connected');
  await pool.query("UPDATE nodes SET last_seen_at=now()-interval '1 hour' WHERE id=$1", [node.id]);
  assert.equal((await diagnostics.readConnectionDiagnostics(actor, node.id)).connectionStatus, 'offline');
  await enrollment.revokeDevice(actor, node.id);
  assert.equal((await diagnostics.readConnectionDiagnostics(actor, node.id)).connectionStatus, 'revoked');
  await enrollment.archiveDevice(actor, node.id);
  await assert.rejects(diagnostics.readConnectionDiagnostics(actor, node.id), /not found/);
  const replacement = await inventory.createNode(actor, { name: `Replacement-${randomUUID()}`, kind: 'branch', mode: 'gateway' });
  const pending = await diagnostics.readConnectionDiagnostics(actor, replacement.id);
  assert.equal(pending.connectionStatus, 'pending');
  assert.equal(pending.enrolledAt, null);
  assert.equal(pending.lastSeenAt, null);
});
