import assert from 'node:assert/strict';
import test from 'node:test';
import pg from 'pg';
import loader from '../support/load-ts.cjs';
assert.equal(process.env.FABRIC_TEST_ISOLATED, '1');
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 8 });
const load = loader({ '../db': { getDatabase: () => pool }, 'next/headers': {}, 'next/navigation': {} });
const drafts = load('src/lib/fabric/network-drafts.ts');
const inventory = load('src/lib/fabric/inventory.ts');
const channel = load('src/lib/fabric/channel.ts');
const actor = (await pool.query('SELECT id::text,email,role FROM operators WHERE email=$1', [process.env.FABRIC_TEST_EMAIL])).rows[0];
test.after(() => pool.end());
test('interface candidates remain inactive, versioned, protected and audited', async () => {
  await pool.query(`INSERT INTO routing_settings(singleton,protected_prefixes,version) VALUES(TRUE,ARRAY['192.168.160.0/24']::cidr[],1)
    ON CONFLICT(singleton) DO UPDATE SET protected_prefixes=excluded.protected_prefixes,version=routing_settings.version+1`);
  const node = await inventory.createNode(actor, { name: 'VLAN draft Hub', kind: 'hub', mode: 'gateway' });
  const initial = await drafts.readNetworkDraft(actor, node.id);
  assert.equal(initial.deploymentAvailable, false);
  assert.equal(initial.draft.version, 0);
  const entry = { interfaceName: 'ens36', vlanId: 100, role: 'lan', mode: 'static', address: '10.87.100.1/24', gateway: null, advertisedPrefix: '10.87.100.0/24', enabled: true, mtu: 1500 };
  const input = { expectedVersion: 0, baseRevision: initial.currentRevision, baseLanVersion: initial.currentLanVersion, interfaces: [entry], safeCommitSeconds: 60 };
  await assert.rejects(drafts.saveNetworkDraft({ ...actor, role: 'viewer' }, node.id, input), /Administrator/);
  await assert.rejects(drafts.readNetworkDraft(null, node.id), /Sign in/);
  await assert.rejects(drafts.saveNetworkDraft(actor, node.id, { ...input, interfaces: [{ ...entry, address: '192.168.160.1/24', advertisedPrefix: '192.168.160.0/24' }] }), /protected/);
  const prior = await channel.desiredConfig(node.id);
  const results = await Promise.allSettled([drafts.saveNetworkDraft(actor, node.id, input), drafts.saveNetworkDraft(actor, node.id, input)]);
  assert.equal(results.filter((r) => r.status === 'fulfilled').length, 1);
  const saved = await drafts.readNetworkDraft(actor, node.id);
  assert.equal(saved.draft.interfaces[0].vlanId, 100);
  assert.equal(saved.draft.safeCommitSeconds, 60);
  assert.equal(saved.draft.version, 1);
  assert.equal((await channel.desiredConfig(node.id)).checksum, prior.checksum);
  assert.equal((await pool.query('SELECT 1 FROM lan_profiles WHERE node_id=$1', [node.id])).rowCount, 0);
  assert.equal((await pool.query("SELECT 1 FROM audit_events WHERE resource_id=$1 AND action='network.draft_saved'", [node.id])).rowCount, 1);
  await assert.rejects(drafts.saveNetworkDraft(actor, node.id, { ...input, expectedVersion: 1, baseRevision: 0 }), /changed/);
  const other = await inventory.createNode(actor, { name: 'VLAN draft overlap', kind: 'branch', mode: 'gateway', lanPrefix: '10.87.101.0/24' });
  await assert.rejects(drafts.saveNetworkDraft(actor, node.id, { ...input, expectedVersion: 1, interfaces: [{ ...entry, address: '10.87.101.1/24', advertisedPrefix: '10.87.101.0/24' }] }), /site network/);
  await pool.query('UPDATE nodes SET archived_at=now() WHERE id=$1', [other.id]);
  await assert.rejects(drafts.readNetworkDraft(actor, other.id), /Active device/);
  await assert.rejects(drafts.saveNetworkDraft(actor, other.id, { ...input, interfaces: [] }), /Active device/);
});
